// Builds site/privacy.html from legal/PRIVACY.md, so the page and the policy never drift apart.
// The policy has one "## <language>" part per language; the page shows the one in ?lang= (else the
// browser's, else English) with a switch between them. Only the Markdown the policy uses is read:
// headings, paragraphs, "- " lists, > quotes, **bold**, `code`, [links](…).
//
//   node site/build-privacy.mjs
import fs from 'node:fs';
import path from 'node:path';

const here = path.dirname(new URL(import.meta.url).pathname);
const md = fs.readFileSync(path.join(here, '../legal/PRIVACY.md'), 'utf8');

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const inline = (s) => esc(s)
  .replace(/`([^`]+)`/g, '<code>$1</code>')
  .replace(/\*\*([^*]+)\*\*/g, '<b>$1</b>')
  .replace(/\[([^\]]+)\]\(([^)]+)\)/g, '<a href="$2">$1</a>');

function blocks(text) {
  const out = [];
  let list = null, quote = null, para = [];
  const flush = () => {
    if (para.length) { out.push(`<p>${inline(para.join(' '))}</p>`); para = []; }
    if (list) { out.push(`<ul>${list.map((li) => `<li>${inline(li)}</li>`).join('')}</ul>`); list = null; }
    if (quote) { out.push(`<blockquote>${quote.map((q) => `<p>${inline(q)}</p>`).join('')}</blockquote>`); quote = null; }
  };
  for (const raw of text.split('\n')) {
    const line = raw.trimEnd();
    if (!line.trim() || line === '---') { flush(); continue; }
    const h = /^(#{2,3}) (.*)$/.exec(line);
    if (h) { flush(); out.push(`<h${h[1].length}>${inline(h[2])}</h${h[1].length}>`); continue; }
    if (line.startsWith('- ')) { if (para.length || quote) flush(); (list ??= []).push(line.slice(2)); continue; }
    if (line.startsWith('> ')) { if (para.length || list) flush(); (quote ??= []).push(line.slice(2)); continue; }
    if (list && /^\s+/.test(raw)) { list[list.length - 1] += ' ' + line.trim(); continue; }
    if (list || quote) flush();
    para.push(line.trim());
  }
  flush();
  return out.join('\n');
}

// Header (title, dates, the note about the original) and one part per language.
const [head, ...rest] = md.split(/\n(?=## )/);
const LANGS = { '한국어': 'ko', 'English': 'en', '日本語': 'ja', 'Português (Brasil)': 'pt', 'Deutsch': 'de', 'Français': 'fr' };
const parts = rest.map((p) => {
  const name = /^## (.*)$/m.exec(p)[1].trim();
  return { name, code: LANGS[name], html: blocks(p.replace(/^## .*\n/, '')) };
}).filter((p) => p.code);
if (parts.length !== 6) throw new Error(`expected 6 languages, found ${parts.map((p) => p.name).join(', ')}`);

const headLines = head.split('\n').filter((l) => l.trim() && !l.startsWith('- [') && !l.startsWith('---'));
const title = headLines.find((l) => l.startsWith('# ')).slice(2);
const meta = headLines.filter((l) => /^[^#>]/.test(l)).map((l) => `<p class="meta-line">${inline(l)}</p>`).join('\n');
const note = headLines.filter((l) => l.startsWith('> ')).map((l) => `<p>${inline(l.slice(2))}</p>`).join('');

const page = `<!doctype html>
<html lang="ko">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>como – Privacy Policy</title>
<link rel="icon" href="assets/favicon.png">
<link rel="stylesheet" href="style.css">
</head>
<body>
<!-- Generated by site/build-privacy.mjs from legal/PRIVACY.md. Edit that file, then run: node site/build-privacy.mjs -->
<div class="wrap">
  <header class="top"><a class="brand" href="./"><img src="assets/icon.png" alt="">como</a></header>
  <main class="doc">
    <h1>${inline(title)}</h1>
    ${meta}
    <blockquote>${note}</blockquote>
    <nav aria-label="Language">
      ${parts.map((p) => `<a href="?lang=${p.code}" data-lang="${p.code}">${esc(p.name)}</a>`).join('\n      ')}
    </nav>
    ${parts.map((p) => `<article class="lang-part" lang="${p.code}" data-lang="${p.code}">\n<h2>${esc(p.name)}</h2>\n${p.html}\n</article>`).join('\n')}
  </main>
</div>
<script>
const LANGS = ${JSON.stringify(parts.map((p) => p.code))};
const pick = (c) => LANGS.find((l) => String(c || '').toLowerCase().startsWith(l));
const lang = pick(new URLSearchParams(location.search).get('lang')) || pick(navigator.languages?.[0] || navigator.language) || 'en';
document.documentElement.lang = lang;
for (const el of document.querySelectorAll('[data-lang]')) {
  if (el.tagName === 'ARTICLE') el.classList.toggle('on', el.dataset.lang === lang);
  else if (el.dataset.lang === lang) el.setAttribute('aria-current', 'page');
}
</script>
</body>
</html>
`;
fs.writeFileSync(path.join(here, 'privacy.html'), page);
console.log(`✓ site/privacy.html (${parts.map((p) => p.code).join(', ')})`);
